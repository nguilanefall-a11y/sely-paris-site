/**
 * Récupère le dictionnaire de libellés pour la langue courante
 */
export function getVehicleUI(langCode = 'fr') {
  const code = String(langCode).toLowerCase().split('-')[0];
  return VEHICLE_UI_STRINGS[code] || VEHICLE_UI_STRINGS.en || VEHICLE_UI_STRINGS.fr;
}

/**
 * Traduit les champs dynamiques d'un véhicule (catégorie, sous-titre, badge, points forts)
 */
export function getLocalizedVehicleData(veh, langCode = 'fr') {
  if (!veh) return veh;
  const isFrench = String(langCode).toLowerCase().startsWith('fr');

  return {
    ...veh,
    category: isFrench ? veh.category : (veh.categoryEn || veh.category),
    subtitle: isFrench ? veh.subtitle : (veh.subtitleEn || veh.subtitle),
    badge: isFrench ? veh.badge : (veh.badgeEn || veh.badge),
    highlights: isFrench ? veh.highlights : (veh.highlightsEn || veh.highlights),
  };
}
